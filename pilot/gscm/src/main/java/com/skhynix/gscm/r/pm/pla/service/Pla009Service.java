    // LLM 포팅됨 - 사람 리뷰 필요(CLAUDE.md: 리뷰 없는 커밋 금지)
public Map<String, Object> fAuthCheck(Map<String, Object> request) {
	Map<String, Object> responseData = new java.util.HashMap<>();
	try {
		// FIXME(원본 버그): 원본은 du.dAuthCheck(requestData, onlineCtx)를 호출하지만 requestData, onlineCtx가 선언되어 있지 않음
		Object result = store.dAuthCheck(requestData, onlineCtx);
		// FIXME(원본 버그): 원본은 반환값에 대해 getRecordSet("AUTH_LIST"), getRecordCount()를 호출하는 NEXCORE 타입 의존 로직임
		Object rs = result.getRecordSet("AUTH_LIST");
		if (rs.getRecordCount() > 0) {
			responseData.put("AUTH_YN", "Y");
		} else {
			responseData.put("AUTH_YN", "N");
		}
	} catch (BizRuntimeException be) {
		throw be;
	} catch (Exception e) {
		throw new BizRuntimeException("E0052", e);
	}
	return responseData;
}

