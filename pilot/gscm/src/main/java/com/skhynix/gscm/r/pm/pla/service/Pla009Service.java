        paramMap.put("METRIC_TYPE", "QTY");
        requestData.putFieldMap(paramMap); // FIXME(원본 버그): requestData 미선언 및 putFieldMap 의존 원본 그대로 유지

        Object rs = store.dPLA00902(requestData).get("DETAIL_LIST"); // FIXME(원본 버그): requestData 미선언 원본 그대로 유지
        responseData.put("DETAIL_LIST", rs);
